//! Service definitions: "run this program, restart it if it dies, start it at boot".
//! A definition is stored as a small text file and turned into an OpenRC script that uses
//! `supervise-daemon`, so services keep running with nobody logged in and without the UI.
//! Nothing here knows about any particular program (Minecraft, bots, web servers ...).
use std::fmt::Write as _;

#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct ServiceDef {
    pub name: String,
    pub description: String,
    /// The whole command line, e.g. `java -Xmx2G -jar server.jar nogui`.
    pub command: String,
    pub dir: String,
    pub user: String,
    pub env: Vec<(String, String)>,
    pub autostart: bool,
}

pub const INIT_PREFIX: &str = "exec85-";

pub fn valid_name(n: &str) -> Result<(), &'static str> {
    if n.is_empty() || n.len() > 32 { return Err("The name must be 1 to 32 characters."); }
    if !n.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_') { return Err("Use only lowercase letters, digits, - and _."); }
    if n.starts_with('-') || n.starts_with('_') { return Err("The name must start with a letter or digit."); }
    Ok(())
}

pub fn valid_env_name(n: &str) -> bool {
    !n.is_empty() && !n.starts_with(|c: char| c.is_ascii_digit()) && n.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

impl ServiceDef {
    pub fn validate(&self) -> Result<(), String> {
        valid_name(&self.name).map_err(String::from)?;
        if self.command.trim().is_empty() { return Err("Enter the command to run.".into()); }
        if self.command.contains('\n') || self.description.contains('\n') { return Err("No line breaks, please.".into()); }
        if !self.dir.is_empty() && !self.dir.starts_with('/') { return Err("The folder must be a full path starting with /.".into()); }
        if self.user.is_empty() || !self.user.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-') { return Err("Enter a valid user name.".into()); }
        for (k, v) in &self.env {
            if !valid_env_name(k) { return Err(format!("'{k}' is not a valid variable name.")); }
            if v.contains('\n') { return Err("No line breaks in variables.".into()); }
        }
        Ok(())
    }

    pub fn init_name(&self) -> String { format!("{INIT_PREFIX}{}", self.name) }
    pub fn log_path(&self) -> String { format!("/var/log/exec85/{}.log", self.name) }
}

/// Quote for a POSIX shell: everything between single quotes.
pub fn sh_quote(s: &str) -> String { format!("'{}'", s.replace('\'', "'\\''")) }

/// Split a command line into words the way a shell would for simple cases (quotes and backslashes).
pub fn split_command(s: &str) -> Result<Vec<String>, String> {
    let (mut out, mut cur, mut have) = (Vec::new(), String::new(), false);
    let mut q: Option<char> = None;
    let mut it = s.chars();
    while let Some(c) = it.next() {
        match (q, c) {
            (Some(qc), c) if c == qc => q = None,
            (Some('"'), '\\') => { if let Some(n) = it.next() { if !matches!(n, '"' | '\\' | '$') { cur.push('\\'); } cur.push(n); } }
            (Some(_), c) => cur.push(c),
            (None, '\'') | (None, '"') => { q = Some(c); have = true; }
            (None, '\\') => { if let Some(n) = it.next() { cur.push(n); have = true; } }
            (None, c) if c.is_whitespace() => { if have || !cur.is_empty() { out.push(std::mem::take(&mut cur)); have = false; } }
            (None, c) => cur.push(c),
        }
    }
    if q.is_some() { return Err("A quote is not closed.".into()); }
    if have || !cur.is_empty() { out.push(cur); }
    if out.is_empty() { return Err("Enter the command to run.".into()); }
    Ok(out)
}

/// The OpenRC script. The program is started by `supervise-daemon`, which restarts it when it exits.
pub fn render_script(d: &ServiceDef) -> Result<String, String> {
    d.validate()?;
    let words = split_command(&d.command)?;
    let mut s = String::new();
    s.push_str("#!/sbin/openrc-run\n# Generated by Exec85. Edit the service in the Services app instead of this file.\n");
    let _ = writeln!(s, "name={}", sh_quote(&d.name));
    let _ = writeln!(s, "description={}", sh_quote(if d.description.is_empty() { &d.name } else { &d.description }));
    s.push_str("supervisor=supervise-daemon\n");
    let _ = writeln!(s, "command={}", sh_quote(&words[0]));
    let args: Vec<String> = words[1..].iter().map(|w| sh_quote(w)).collect();
    let _ = writeln!(s, "command_args={}", sh_quote(&args.join(" ")).replace("'\\''", "'\\''"));
    let _ = writeln!(s, "command_user={}", sh_quote(&d.user));
    if !d.dir.is_empty() { let _ = writeln!(s, "directory={}", sh_quote(&d.dir)); }
    let _ = writeln!(s, "output_log={}", sh_quote(&d.log_path()));
    let _ = writeln!(s, "error_log={}", sh_quote(&d.log_path()));
    s.push_str("respawn_delay=2\nrespawn_max=0\n");
    for (k, v) in &d.env { let _ = writeln!(s, "export {k}={}", sh_quote(v)); }
    s.push_str("\ndepend() {\n\tneed localmount\n\tuse net\n}\n\nstart_pre() {\n\tcheckpath --directory --owner root:root --mode 0755 /var/log/exec85\n}\n");
    Ok(s)
}

/// The stored definition (what the UI reads back and edits). One `key=value` per line; values are percent-escaped for `%` and newlines only.
pub fn render_conf(d: &ServiceDef) -> String {
    let esc = |s: &str| s.replace('%', "%25").replace('\n', "%0A");
    let mut s = format!("name={}\ndescription={}\ncommand={}\ndir={}\nuser={}\nautostart={}\n", esc(&d.name), esc(&d.description), esc(&d.command), esc(&d.dir), esc(&d.user), d.autostart);
    for (k, v) in &d.env { let _ = writeln!(s, "env.{k}={}", esc(v)); }
    s
}

pub fn parse_conf(text: &str) -> Option<ServiceDef> {
    let unesc = |s: &str| s.replace("%0A", "\n").replace("%25", "%");
    let mut d = ServiceDef::default();
    for line in text.lines() {
        let Some((k, v)) = line.split_once('=') else { continue };
        let v = unesc(v);
        match k {
            "name" => d.name = v, "description" => d.description = v, "command" => d.command = v, "dir" => d.dir = v, "user" => d.user = v,
            "autostart" => d.autostart = v == "true",
            _ => if let Some(e) = k.strip_prefix("env.") { d.env.push((e.to_string(), v)); },
        }
    }
    if d.name.is_empty() { None } else { Some(d) }
}

/// What `rc-service <name> status` printed, as a simple state.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status { Running, Stopped, Crashed, Unknown }

pub fn parse_status(text: &str) -> Status {
    let t = text.to_lowercase();
    if t.contains("started") || t.contains("running") { Status::Running }
    else if t.contains("crashed") { Status::Crashed }
    else if t.contains("stopped") || t.contains("inactive") { Status::Stopped }
    else { Status::Unknown }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn def() -> ServiceDef {
        ServiceDef { name: "mc".into(), description: "Minecraft".into(), command: "java -Xmx2G -jar server.jar nogui".into(), dir: "/srv/mc".into(), user: "tester".into(), env: vec![("JAVA_OPTS".into(), "-Dx=1".into())], autostart: true }
    }

    #[test]
    fn names_and_fields_are_checked() {
        assert!(def().validate().is_ok());
        for bad in ["", "Mc", "a b", "-x", "a/b", &"x".repeat(33)] { assert!(valid_name(bad).is_err(), "{bad:?}"); }
        let mut d = def(); d.command = "  ".into(); assert!(d.validate().is_err());
        let mut d = def(); d.dir = "relative".into(); assert!(d.validate().is_err());
        let mut d = def(); d.user = "a;b".into(); assert!(d.validate().is_err());
        let mut d = def(); d.env = vec![("1X".into(), "v".into())]; assert!(d.validate().is_err());
        let mut d = def(); d.command = "a\nb".into(); assert!(d.validate().is_err());
    }

    #[test]
    fn command_lines_split_like_a_shell() {
        assert_eq!(split_command("java -jar a.jar").unwrap(), ["java", "-jar", "a.jar"]);
        assert_eq!(split_command(r#"node "my bot.js" --name='A B'"#).unwrap(), ["node", "my bot.js", "--name=A B"]);
        assert_eq!(split_command(r"echo a\ b").unwrap(), ["echo", "a b"]);
        assert_eq!(split_command(r#"echo "" x"#).unwrap(), ["echo", "", "x"]);
        assert!(split_command("echo 'open").is_err());
        assert!(split_command("   ").is_err());
    }

    #[test]
    fn quoting_survives_a_real_shell() {
        for s in ["plain", "with space", "it's", "$HOME `x` \"q\"", "a;b&&c", ""] {
            let out = std::process::Command::new("/bin/sh").arg("-c").arg(format!("printf %s {}", sh_quote(s))).output().unwrap();
            assert_eq!(String::from_utf8_lossy(&out.stdout), s);
        }
    }

    #[test]
    fn the_script_has_what_openrc_needs() {
        let s = render_script(&def()).unwrap();
        for want in ["#!/sbin/openrc-run", "supervisor=supervise-daemon", "command='java'", "command_user='tester'", "directory='/srv/mc'",
                     "respawn_max=0", "output_log='/var/log/exec85/mc.log'", "export JAVA_OPTS='-Dx=1'", "use net"] {
            assert!(s.contains(want), "missing {want} in:\n{s}");
        }
        assert!(s.contains("command_args=") && s.contains("-Xmx2G") && s.contains("nogui"));
    }

    #[test]
    fn the_script_is_valid_shell_and_hostile_input_cannot_inject() {
        let mut d = def();
        d.description = "x'; rm -rf / #".into();
        d.command = "echo 'a b' \"c;d\" $(reboot)".into();
        d.env = vec![("V".into(), "'; reboot; '".into())];
        let s = render_script(&d).unwrap();
        // Load the generated script (minus the openrc shebang) in a real shell and print what it defines.
        let probe = format!("{}\nprintf '%s\\n' \"$description\" \"$command\" \"$command_args\" \"$V\"", s.lines().skip(1).collect::<Vec<_>>().join("\n"));
        let out = std::process::Command::new("/bin/sh").arg("-c").arg(probe.replace("\ndepend()", "\ndepend()")).output().unwrap();
        let o = String::from_utf8_lossy(&out.stdout).to_string();
        let l: Vec<&str> = o.lines().collect();
        assert_eq!(l[0], "x'; rm -rf / #");
        assert_eq!(l[1], "echo");
        assert_eq!(l[2], "'a b' 'c;d' '$(reboot)'", "arguments stay literal text: {o}");
        assert_eq!(l[3], "'; reboot; '");
    }

    #[test]
    fn stored_definitions_round_trip() {
        let mut d = def();
        d.description = "100% sure\nsecond line".into();
        d.env.push(("EMPTY".into(), "".into()));
        assert_eq!(parse_conf(&render_conf(&d)).unwrap(), d);
        assert!(parse_conf("nonsense").is_none());
    }

    #[test]
    fn status_text_is_understood() {
        assert_eq!(parse_status(" * status: started"), Status::Running);
        assert_eq!(parse_status(" * status: crashed"), Status::Crashed);
        assert_eq!(parse_status(" * status: stopped"), Status::Stopped);
        assert_eq!(parse_status("???"), Status::Unknown);
    }
}
