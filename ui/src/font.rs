/// Shown for characters the font does not have (accents etc. come later).
const UNKNOWN: Glyph = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"];

#[rustfmt::skip]
const TALL: [(char, Tall); 5] = [
    ('g', [".....", ".....", ".####", "#...#", "#...#", "#...#", ".####", "....#", ".###."]),
    ('j', ["...#.", ".....", "..##.", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##.."]),
    ('p', [".....", ".....", "#.##.", "##..#", "#...#", "#...#", "####.", "#....", "#...."]),
    ('q', [".....", ".....", ".##.#", "#..##", "#...#", "#...#", ".####", "....#", "....#"]),
    ('y', [".....", ".....", "#...#", "#...#", "#...#", "#...#", ".####", "....#", ".###."]),
];

/// Rows of pixels for a character (7 rows, or 9 for letters with tails).
pub fn glyph(c: char) -> &'static [&'static str] {
    if let Some((_, g)) = TALL.iter().find(|(t, _)| *t == c) { return g; }
    let n = c as u32;
    if (32..=126).contains(&n) { &GLYPHS[(n - 32) as usize] } else { &UNKNOWN }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn every_glyph_is_5_by_7_pixels() {
        for g in GLYPHS.iter().chain(std::iter::once(&UNKNOWN)) {
            for row in g { assert_eq!(row.len(), W, "bad row {row:?}"); assert!(row.chars().all(|c| c == '#' || c == '.')); }
        }
        for (_, g) in TALL.iter() { for row in g { assert_eq!(row.len(), W); } }
    }
    #[test]
    fn letters_are_not_blank_and_all_distinct_from_each_other() {
        for c in ('A'..='Z').chain('a'..='z').chain('0'..='9') {
            assert!(glyph(c).iter().any(|r| r.contains('#')), "{c} is blank");
        }
        let mut seen = std::collections::HashSet::new();
        for c in (33u8..=126).map(|b| b as char) { assert!(seen.insert(glyph(c).to_vec()), "{c} duplicates another glyph"); }
    }
}
